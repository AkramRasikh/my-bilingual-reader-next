import {execa} from 'execa';
import {mkdtemp, readdir, readFile, rm} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
type Cue = {start: number; end: number; text: string};
type Track = {code: string; auto: boolean};
const codes: Record<string, string[]> = {chinese: ['zh-CN', 'zh-Hans', 'zh-Hant', 'zh-TW', 'zh-HK', 'zh'], english: ['en', 'en-US', 'en-GB'],
  japanese: ['ja'], french: ['fr'], arabic: ['ar']};
export function chooseTrack(info: {subtitles?: object; automatic_captions?: object}, language: string): Track | null {
  const prefixes = codes[language];
  if (!prefixes) return null;
  for (const [tracks, auto] of [[info.subtitles, false], [info.automatic_captions, true]] as const) {
    const available = Object.keys(tracks || {}).filter(code => prefixes.some(prefix => code === prefix || code.startsWith(prefix + '-')))
      .filter(code => /^[A-Za-z0-9-]+$/.test(code));
    available.sort((a, b) => {
      const rank = (code: string) => {const index = prefixes.indexOf(code); return index >= 0 ? index : prefixes.length + code.length;};
      return rank(a) - rank(b);
    });
    if (available[0]) return {code: available[0], auto};
  }
  return null;
}
const clean = (text: string) => text.replace(/\s+/g, ' ').trim();
export function parseSubtitle(text: string, json: boolean): Cue[] {
  if (json) return (JSON.parse(text).events || []).flatMap((event: {tStartMs: number; dDurationMs: number; segs?: {utf8?: string}[]}) => {
    const start = Number(event.tStartMs) / 1000, duration = Number(event.dDurationMs) / 1000;
    const value = clean((event.segs || []).map(segment => segment.utf8 || '').join(''));
    return value && Number.isFinite(start) && start >= 0 && Number.isFinite(duration) && duration > 0
      ? [{start, end: start + duration, text: value}] : [];
  });
  const seconds = (stamp: string) => stamp.split(':').reduce((total, part) => total * 60 + Number(part.replace(',', '.')), 0);
  const cues: Cue[] = [];
  for (const block of text.replace(/\r/g, '').split(/\n\s*\n/)) {
    const lines = block.split('\n');
    const index = lines.findIndex(line => /\d.*-->/.test(line));
    if (index < 0) continue;
    const match = lines[index].match(/([\d:.,]+)\s+-->\s+([\d:.,]+)/);
    if (!match) continue;
    const start = seconds(match[1]), end = seconds(match[2]);
    const value = clean(lines.slice(index + 1).join(' ').replace(/<[^>]*>/g, '')
      .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&'));
    if (value && Number.isFinite(start) && Number.isFinite(end) && start >= 0 && end > start) cues.push({start, end, text: value});
  }
  return cues;
}
const common = ['--skip-download', '--no-playlist', '--no-warnings', '--retries', '0', '--extractor-retries', '0', '--fragment-retries', '0', '--socket-timeout', '10'];
async function downloadTrack(url: string, track: Track, directory: string, name: string) {
  await execa('yt-dlp', [...common, track.auto ? '--write-auto-subs' : '--write-subs', '--sub-langs', track.code,
    '--sub-format', 'json3/vtt', '-o', path.join(directory, name + '.%(ext)s'), url], {timeout: 20000});
  const files = await readdir(directory);
  const file = files.find(file => file.startsWith(name + '.') && file.endsWith('.json3')) || files.find(file => file.startsWith(name + '.') && file.endsWith('.vtt'));
  if (!file) throw new Error('No subtitle file was produced.');
  const segments = parseSubtitle(await readFile(path.join(directory, file), 'utf8'), file.endsWith('.json3'));
  if (!segments.length) throw new Error('No readable subtitle lines were returned.');
  return {status: 'ready' as const, segments, trackLanguage: track.code, isAutoGenerated: track.auto};
}
export async function fetchLocalSubtitles(videoId: string, language: string, includeEnglish: boolean) {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'checkpoint-subs-'));
  try {
    const url = `https://www.youtube.com/watch?v=${videoId}`;
    const {stdout} = await execa('yt-dlp', [...common, '--dump-single-json', url], {timeout: 20000, maxBuffer: 50 * 1024 * 1024});
    const info = JSON.parse(stdout), track = chooseTrack(info, language);
    if (!track) throw new Error('No study-language subtitle track was found.');
    const target = await downloadTrack(url, track, directory, 'target');
    let english: Awaited<ReturnType<typeof downloadTrack>> | {status: 'unavailable'; reason: string} | null = null;
    if (includeEnglish) {
      const englishTrack = chooseTrack(info, 'english');
      if (englishTrack) {
        try {english = await downloadTrack(url, englishTrack, directory, 'english');}
        catch {english = {status: 'unavailable', reason: 'English retrieval failed; study-language captions are available.'};}
      } else english = {status: 'unavailable', reason: 'No English track found; study-language captions are available.'};
    }
    return {target, english};
  } finally {await rm(directory, {recursive: true, force: true});}
}
